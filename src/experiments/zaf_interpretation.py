"""Day 27: model interpretation and portfolio-safe limitation wording.

Fits the day-ahead logistic once on the **whole** labelled period to read
the *structure* of the model, and is explicit that this fit is descriptive
only: every performance claim in this project comes from the walk-forward
protocol (`day18`), never from this in-sample fit.

What the coefficients can and cannot say
----------------------------------------

* Coefficients are on standardized inputs, so magnitudes are comparable.
* Weather features are correlated (temp/gust/pressure move together), so
  credit is split arbitrarily among them — a coefficient is *not* a causal
  effect, and the ablation (`day21`) is the honest source for "how much
  does weather add".
* The dominant block is persistence (label lags): yesterday's observed
  shedding. That is operationally true and expected; the project says so
  rather than dressing it up as a weather-prediction win.

Usage:
    python -m src.experiments.zaf_interpretation
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

from src.config import DATA_PROCESSED, REPORTS_DIR
from src.datasets.zaf_daily import build_dataset
from src.experiments.zaf_ablation import (
    CALENDAR_FEATURES, CITY_PREFIXES, LABEL_LAG_PREFIXES,
)
from src.experiments.zaf_daily_model import (
    logistic_pipeline, prepare_frame,
)
from src.models.base import SklearnRiskModel


def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def feature_group(name: str) -> str:
    """Which block a feature belongs to (interpretation buckets)."""
    if name.startswith(LABEL_LAG_PREFIXES):
        return "persistence (label lags)"
    if name.startswith(CITY_PREFIXES):
        return "weather (lag/rolling)"
    if name in CALENDAR_FEATURES:
        return "calendar (advance-known)"
    return "other"


def fit_interpretation_model(frame: pd.DataFrame | None = None) -> dict:
    """Descriptive full-period fit + coefficient table (not a score card)."""
    if frame is None:
        frame = build_dataset()
    X, y, n_dropped, dates = prepare_frame(frame)

    model = SklearnRiskModel(logistic_pipeline())
    model.fit(X, y)
    clf = model.estimator.named_steps["clf"]
    coefs = clf.coef_[0]

    table = pd.DataFrame({
        "feature": list(X.columns),
        "coef_standardized": coefs,
    })
    table["group"] = table["feature"].map(feature_group)
    table["abs_coef"] = table["coef_standardized"].abs()
    table = table.sort_values("abs_coef", ascending=False).reset_index(drop=True)

    group_share = (table.groupby("group")["abs_coef"].sum()
                   / table["abs_coef"].sum())
    return {
        "n_rows": len(X),
        "n_dropped_nan_lags": n_dropped,
        "n_features": X.shape[1],
        "prevalence": float(y.mean()),
        "coefficients": table,
        "group_share": group_share,
        "dates": dates,
    }


def write_outputs(result: dict, out_dir: Path | None = None) -> Path:
    out_dir = out_dir or DATA_PROCESSED
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "zaf_feature_coefficients.csv"
    result["coefficients"].drop(columns=["abs_coef"]).to_csv(path, index=False)
    return path


def write_report(result: dict, out_path: Path | None = None) -> Path:
    out_path = out_path or (REPORTS_DIR / "day27_model_interpretation.md")
    out_path.parent.mkdir(parents=True, exist_ok=True)

    top = result["coefficients"].head(15)
    share = result["group_share"]
    n_by_group = result["coefficients"].groupby("group").size()
    share_md = "\n".join(
        f"| {g} | {100 * v:.1f}% | {int(n_by_group.get(g, 0))} |"
        for g, v in share.items())
    top_md = top[["feature", "coef_standardized", "group"]].to_markdown(index=False)

    text = f"""# Day 27 — Model interpretation and portfolio-safe wording

Generated by `python -m src.experiments.zaf_interpretation` on {_utc_now()}.

**Descriptive fit only.** One logistic regression over the full labelled
period ({result['n_rows']} days, {result['n_features']} features, positive
rate {result['prevalence']:.3f}) to read the model's *structure*. All
performance numbers remain the walk-forward ones (`day18`): Brier 0.0457 vs
0.2338 for the pinned climatology baseline, skill +0.794.

## Where the model's weight sits (share of total |standardized coefficient|)

*Coefficient mass, not skill — weather's share is inflated by feature count
and correlation; read the ablation (`day21`) for what actually predicts.*

| feature block | share of coefficient mass | #features |
|---|---|---|
{share_md}

## Top 15 features by |standardized coefficient|

{top_md}

## How to read this

- **Coefficient mass is not skill.** The block share above is inflated by
  feature count: 111 correlated weather features split credit among
  themselves, while 6 label-lag features share one signal. The two
  *largest individual* coefficients are persistence lags
  (`mlr_mw_mean_lag_1`, `hours_active_lag_1`).
- **The ablation is the arbiter of skill**, not the coefficient table: the
  label-lag-only model reaches Brier 0.0196 while the full 122-feature model
  reaches 0.0457 — adding the weather block makes prediction *worse*
  (`day21`). So the honest reading is: **persistence drives the skill; the
  weather coefficients mostly fit noise.**
- **Weather is real but secondary, and correlated features share credit
  arbitrarily** — a coefficient is not a causal effect.
- **Calendar features** are advance-known and contribute little, as
  expected.

## Portfolio-safe wording (use this)

> A day-ahead probabilistic model of **national** load-shedding in South
> Africa, trained on Eskom's Manual Load Reduction series (2017-2026) with
> strictly-past weather and calendar features, evaluated walk-forward
> against a pinned climatology baseline (Brier skill +0.79 over 1,350
> out-of-fold days). Its skill is dominated by persistence in the shedding
> state; weather adds standalone signal but little beyond persistence.
> Kenya and Nigeria are covered by **label provenance and coverage
> analysis**, not by a claimed outage model.

## Wording to avoid (and why)

| do not say | why |
|---|---|
| "we predict power outages in Kenya/South Africa/Nigeria" | only ZAF has an evaluated model; NGA has 2 test positives; KEN has no unplanned labels |
| "weather-driven outage prediction" | ablation shows weather adds ~0 on top of persistence (`day21`) |
| "accurate outage probabilities" | probabilities are national, day-ahead, and calibrated on OOF rows only (`day19`) |
| "grid collapse risk in Nigeria" | NGA model deliberately not claimed (`day20`) |
| any sub-national probability | no sub-national label exists for any country |
"""
    out_path.write_text(text, encoding="utf-8")
    print(f"Day 27 interpretation report written to {out_path}")
    return out_path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args(argv)
    result = fit_interpretation_model()
    path = write_outputs(result)
    print(f"wrote coefficients: {path}")
    write_report(result)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
