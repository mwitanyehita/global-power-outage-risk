"""Day 20: NGA collapse-day labels — honest baselines for a rare event.

The NGA target is a *national grid-collapse day* (Day 17 labels, 14 positives
in 2023-2025, 1.3% prevalence). The honest deliverable here is not a model:
two positives in a one-year test window cannot support one. This module

* reads the Day 17 daily labels,
* runs a chronological 2023-24 train / 2025 test split,
* scores the only defensible baselines (constant training prevalence, and the
  observed 2025 rate as an oracle reference for reading the gap),
* and writes down exactly what would be required before any weather-linked
  NGA model is claimed.

Ranking metrics are reported but marked as unstable at this sample size —
with 2 positives, PR-AUC moves in jumps and must not be quoted as skill.

Usage:
    python -m src.experiments.nga_baseline
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score

from src.config import DATA_PROCESSED, REPORTS_DIR
from src.evaluation.probabilistic import brier_score, log_loss, roc_auc

DAILY_CSV = DATA_PROCESSED / "nga_daily_collapse.csv"
TRAIN_END_YEAR = 2024  # train 2023-2024, test 2025


def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def load_daily(daily_csv: Path | None = None) -> pd.DataFrame:
    """Day 17 daily labels (rebuilt from NERC events if the CSV is absent)."""
    path = daily_csv or DAILY_CSV
    if path.exists():
        df = pd.read_csv(path)
    else:
        from src.labels.collapse_days import (
            daily_collapse_labels, load_events,
        )
        df = daily_collapse_labels(load_events())
        df["date"] = df["date"].dt.strftime("%Y-%m-%d")
    df["date"] = pd.to_datetime(df["date"])
    return df.sort_values("date").reset_index(drop=True)


def evaluate(daily: pd.DataFrame,
             train_end_year: int = TRAIN_END_YEAR) -> dict:
    """Chronological split; score constant-prevalence forecasts."""
    train = daily[daily["date"].dt.year <= train_end_year]
    test = daily[daily["date"].dt.year > train_end_year]
    if train.empty or test.empty:
        raise ValueError("split produced an empty train or test window")

    y_train = train["collapse_any"].astype(int).to_numpy()
    y_test = test["collapse_any"].astype(int).to_numpy()
    p_train = float(y_train.mean())

    p_const = np.full(len(y_test), p_train, dtype=float)
    p_oracle = np.full(len(y_test), float(y_test.mean()), dtype=float)

    def _safe(fn, y, p):
        return float(fn(y, p)) if len(np.unique(y)) >= 2 else float("nan")

    return {
        "train_days": len(train),
        "test_days": len(test),
        "train_positives": int(y_train.sum()),
        "test_positives": int(y_test.sum()),
        "train_rate": p_train,
        "test_rate": float(y_test.mean()),
        "const_brier": float(brier_score(y_test, p_const)),
        "const_log_loss": float(log_loss(y_test, p_const)),
        "const_pr_auc": _safe(average_precision_score, y_test, p_const),
        "const_roc_auc": _safe(roc_auc, y_test, p_const),
        "oracle_brier": float(brier_score(y_test, p_oracle)),
        "test_dates": test["date"],
        "y_test": y_test,
        "p_const": p_const,
    }


def write_report(result: dict, out_path: Path | None = None) -> Path:
    out_path = out_path or (REPORTS_DIR / "day20_nga_baseline.md")
    out_path.parent.mkdir(parents=True, exist_ok=True)

    text = f"""# Day 20 — NGA collapse days: honest baselines, no model claimed

Generated by `python -m src.experiments.nga_baseline` on {_utc_now()}.

## Split (chronological, no shuffling)

| window | days | positives | prevalence |
|---|---|---|---|
| train (2023-{TRAIN_END_YEAR}) | {result['train_days']} | {result['train_positives']} | {result['train_rate']:.4f} |
| test ({TRAIN_END_YEAR + 1}) | {result['test_days']} | {result['test_positives']} | {result['test_rate']:.4f} |

## Baselines scored on the test window

| forecast | brier | log_loss | pr_auc | roc_auc |
|---|---|---|---|---|
| constant training prevalence ({result['train_rate']:.4f}) | {result['const_brier']:.6f} | {result['const_log_loss']:.4f} | {result['const_pr_auc']:.3f} | {result['const_roc_auc']:.3f} |
| oracle test prevalence ({result['test_rate']:.4f}) | {result['oracle_brier']:.6f} | — | — | — |

## Verdict: no NGA model is claimed

- **{result['test_positives']} positive days in the test year.** Any classifier
  fitted across 14 positives would be memorizing, not learning; presenting
  probabilities from such a fit would violate the project's own bar
  (\"do not publish unsupported outage probabilities\").
- **Weather linkage is speculative.** Grid collapses are driven by system
  adequacy, transmission faults and gas supply — the physical case for
  city-level weather as a daily predictor is not established, so none is
  asserted.
- The baseline is genuinely hard to beat: the constant training rate is the
  honest floor, and the oracle gap
  ({result['const_brier'] - result['oracle_brier']:+.6f} Brier) shows the
  entire headroom available to a perfect *rate* forecast.

## Requirements before an NGA model may be claimed

1. A labelable series long enough for walk-forward validation with
   **>= 12 positives in every test year** (currently 2 in 2025).
2. Dated events back-filled to 2019-2022 — blocked: those NERC reports were
   never published / carry counts only (Day 10, Day 17).
3. A sub-national outage signal (the current target is national-only, so
   city weather is misaligned by construction).
4. A documented causal mechanism test, not just feature importance on 14
   events.

Until then the honest product is the **label + its provenance**, not a
prediction.
"""
    out_path.write_text(text, encoding="utf-8")
    print(f"Day 20 NGA baseline report written to {out_path}")
    return out_path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args(argv)
    result = evaluate(load_daily())
    write_report(result)
    print(f"train {result['train_positives']}/{result['train_days']}, "
          f"test {result['test_positives']}/{result['test_days']}, "
          f"const brier {result['const_brier']:.6f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
